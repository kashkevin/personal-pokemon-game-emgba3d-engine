#!/usr/bin/env python3
"""The size of each script special's result, for the PC game's `specialvar` (KNOWN_ISSUES MS-166).

The script engine calls every special through `u16 (*)(void)` (src/scrcmd.c) and stores its result in a variable.
A special declared to return an 8-bit value (bool8, u8, s8) defines only the low byte of the PC's return register;
the rest is whatever the function computed last. IsEnoughForCostInVar0x8005 ends with `setae %al` after reading
the money, so with 3,000 in hand its TRUE read 2,817 and the Day Care said there was not enough money. The GBA's
compiler widens the byte; the PC game narrows each such result to its byte, from the table this writes:
data/specials.inc gives each special's number, its C definition under src/ its type.

    python3 tools/pc_port/special_results.py           # write src/data/script_special_results.h
    python3 tools/pc_port/special_results.py --check   # exit 1 when the header is not what the sources give
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "src/data/script_special_results.h"
SPECIAL = re.compile(r"^\s*def_special\s+(\w+)", re.M)
# a function's definition: its storage class, return type, name and parameters, then its body's brace (a special
# is never static: the table names it from another file)
DEFINITION = re.compile(r"^((?:(?:static|inline|UNUSED|NOINLINE)\s+)*)([A-Za-z_][\w \t]*?[\w\*])[ \t]*\**[ \t]*(\w+)"
                        r"\s*\([^;{}()]*\)\s*\n?\s*\{", re.M)
UNSIGNED_BYTE = {"bool8", "u8", "unsigned char", "bool"}
SIGNED_BYTE = {"s8", "signed char"}
WIDER = {"void", "u16", "s16", "bool16", "u32", "s32", "bool32", "int", "unsigned int", "uintptr_t", "UNUSED void",
         "void UNUSED"}


def result_bytes(type_name: str) -> int:
    """1 for an 8-bit unsigned result, -1 for an 8-bit signed one, 0 for anything else (a wider value, or none)."""
    if type_name in UNSIGNED_BYTE:
        return 1
    if type_name in SIGNED_BYTE:
        return -1
    if type_name in WIDER or type_name.startswith("enum ") or type_name.endswith("*"):
        return 0
    raise ValueError(f"unknown return type {type_name!r}")


def collect() -> tuple[list[str], dict[str, set[str]]]:
    names = SPECIAL.findall((ROOT / "data/specials.inc").read_text())
    wanted, types = set(names), {}
    for path in sorted((ROOT / "src").rglob("*.c")):
        text = path.read_text(errors="replace")
        for match in DEFINITION.finditer(text):
            if match.group(3) in wanted and "static" not in match.group(1).split():
                types.setdefault(match.group(3), set()).add(" ".join(match.group(2).split()))
    return names, types


def render() -> str:
    names, types = collect()
    rows, problems = [], []
    for index, name in enumerate(names):
        found = types.get(name)
        if not found:
            problems.append(f"{name}: no definition under src/")
            continue
        try:
            sizes = {result_bytes(t) for t in found}
        except ValueError as error:
            problems.append(f"{name}: {error}")
            continue
        if len(sizes) != 1:
            problems.append(f"{name}: definitions of different sizes {sorted(found)}")
            continue
        size = sizes.pop()
        if size:
            rows.append(f"    [{index}] = {size}, // {name} ({' / '.join(sorted(found))})")
    if problems:
        raise SystemExit("special_results.py:\n  " + "\n  ".join(problems))
    return "\n".join([
        "// Generated by tools/pc_port/special_results.py from data/specials.inc and the specials' definitions under",
        "// src/: do not edit. The PC game's specialvar narrows the result of each special listed here to its byte, as the",
        "// GBA's compiler widens it (KNOWN_ISSUES MS-166): 1 an 8-bit unsigned result (bool8, u8), -1 an 8-bit signed",
        "// one (s8). Every other special's result is 16 bits or more, or none.",
        "#ifndef GUARD_DATA_SCRIPT_SPECIAL_RESULTS_H",
        "#define GUARD_DATA_SCRIPT_SPECIAL_RESULTS_H",
        "",
        f"#define SCRIPT_SPECIAL_COUNT {len(names)}",
        "",
        "static const s8 sScriptSpecialResultBytes[SCRIPT_SPECIAL_COUNT] =",
        "{",
        *rows,
        "};",
        "",
        "#endif // GUARD_DATA_SCRIPT_SPECIAL_RESULTS_H",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the header instead of writing it")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is not current: run tools/pc_port/special_results.py", file=sys.stderr)
            return 1
        print(f"special results: {text.count('] = ')} of {text.split('SCRIPT_SPECIAL_COUNT ')[1].split()[0]} specials "
              "narrowed to a byte; the header is current")
        return 0
    HEADER.write_text(text)
    print(f"wrote {HEADER.relative_to(ROOT)}: {text.count('] = ')} specials narrowed to a byte")
    return 0


if __name__ == "__main__":
    sys.exit(main())
