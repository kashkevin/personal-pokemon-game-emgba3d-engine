#!/usr/bin/env python3
"""The PC game's teachable learnsets (the owner's rule of 2026-10-27).

"if a pokemon can learn an unusual move in a certain special way that special way should be the only way; if our game
doesnt support those ways then that pokemon cant learn it". The expansion's teachable_learnsets.h lets a TM or a tutor
teach a species any move it learns by any means in any game it covers (level, egg, tutor, TM; tools/learnset_helpers/
make_teachables.py). Here a TM or a tutor (both teach) keeps a move only where an official game teaches that species
the move by TM or tutor (the porymoves files' TMMoves and TutorMoves); a move it gets only by level, egg or a
pre-evolution is learnt only that way. Nothing is added: each learnset is the expansion's with those moves taken out.
A species the porymoves files do not name keeps the expansion's learnset. Pokemon that already know a move keep it
(the game reads these lists only to teach).

    python3 tools/learnset_helpers/make_teachables_pc.py [OUTPUT]     (default src/data/pokemon/teachable_learnsets_pc.h)

Reads src/data/pokemon/teachable_learnsets.h (make_teachables.py's output, the GBA build's) and
tools/learnset_helpers/porymoves_files/*.json. The GBA build keeps teachable_learnsets.h; src/pokemon.c includes this
file instead under PORTABLE.
"""
import json
import pathlib
import re
import sys
import unicodedata

LEARNSET = re.compile(r"static const u16 s(\w+)TeachableLearnset\[\] = \{(.*?)\};", re.S)
SNAKIFY = re.compile(r"(?!^)([A-Z]+)")


def species_key(name: str) -> str:
    """make_teachables.py's own conversion: sRaichuAlolaTeachableLearnset -> RAICHU_ALOLA."""
    return SNAKIFY.sub(r"_\1", name).upper()


def official_teaching(files) -> dict[str, set[str]]:
    taught: dict[str, set[str]] = {}
    for path in files:
        with open(path, "r") as fp:
            for species, by_method in json.load(fp).items():
                # FLABÉBÉ -> FLABEBE, as the learnset's name spells it
                species = unicodedata.normalize("NFKD", species).encode("ascii", "ignore").decode()
                moves = taught.setdefault(species, set())
                moves.update(by_method.get("TMMoves", []))
                moves.update(by_method.get("TutorMoves", []))
    return taught


def main() -> int:
    output = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "src/data/pokemon/teachable_learnsets_pc.h")
    source = pathlib.Path("src/data/pokemon/teachable_learnsets.h").read_text()
    taught = official_teaching(sorted(pathlib.Path("tools/learnset_helpers/porymoves_files").glob("*.json")))
    removed = kept_as_is = 0

    def strip(match: re.Match) -> str:
        nonlocal removed, kept_as_is
        name, body = match.group(1), match.group(2)
        moves = re.findall(r"MOVE_[A-Z0-9_]+", body)
        key = species_key(name)
        if key not in taught or name == "None":
            kept_as_is += 1
            return match.group(0)
        keep = [m for m in moves if m == "MOVE_UNAVAILABLE" or m in taught[key]]
        removed += len(moves) - len(keep)
        return f"static const u16 s{name}TeachableLearnset[] = {{\n    " + ",\n    ".join(keep) + ",\n};"

    content = LEARNSET.sub(strip, source)
    content = content.replace("// DO NOT MODIFY THIS FILE! It is auto-generated by tools/learnset_helpers/make_teachables.py",
                              "// DO NOT MODIFY THIS FILE! It is auto-generated by tools/learnset_helpers/make_teachables_pc.py\n"
                              "// from teachable_learnsets.h: the PC game's TM and tutor learnsets (the owner's rule of 2026-10-27)", 1)
    output.write_text(content)
    print(f"{output}: {removed} moves taken out; {kept_as_is} learnsets kept as they are (no official data)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
