#!/usr/bin/env python3
"""The Game Corner's TM CATALOGUE (the PC game; the owner's TM catalogue of 2026-10-31, docs/owner-decisions.md 26-29).

Every TM of the game (TM01-TM168: include/constants/tms_hms.h and tms_hms_pc.h) in one of four kinds - Physical Attack,
Special Attack, Status and Setup, Defensive and Utility - at the owner's prices: 1,000 / 2,500 / 5,000 / 7,500 / 10,000
coins by usefulness, and the five TMs the prize counter already sold at their own prices (TM13, TM24, TM29, TM32, TM35:
the same TM costs the same at both). The data is tools/mp/tm_catalogue.json (one row per TM: number, move, name, type,
kind, coins); this script writes the shop's four lists and its price table:

    data/scripts/mp_tm_catalogue_lists.inc   the coin shop's lists (pokemart), by TM number within each kind
    src/platform/mp_tm_catalogue.h           the coin price of every TM and the lists (src/platform/coin_shop.c)

Data scripts are assembled without the PC build's C definitions, so TM101-TM168 (items 874-941, PC only) are written as
numbers, each with its name. Run from the engine root: python3 tools/mp/gen_tm_catalogue.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KINDS = [("Physical Attack", "TmPhysical"), ("Special Attack", "TmSpecial"), ("Status and Setup", "TmStatus"),
         ("Defensive and Utility", "TmUtility")]
FIRST_PC_ITEM = 874     # TM101 (include/constants/items.h); TM n >= 101 is item 773 + n


def item(tm):
    return f"ITEM_TM{tm:02d}" if tm <= 100 else str(773 + tm)


def main():
    rows = json.load(open(os.path.join(ROOT, "tools", "mp", "tm_catalogue.json")))
    if [r["tm"] for r in rows] != list(range(1, len(rows) + 1)):
        sys.exit("tm_catalogue.json: the TMs must be TM01, TM02, ... in order")
    kinds = {k for k, _ in KINDS}
    for r in rows:
        if r["category"] not in kinds or not isinstance(r["coins"], int) or r["coins"] <= 0:
            sys.exit(f"tm_catalogue.json: TM{r['tm']:02d} has kind {r['category']!r} and coins {r['coins']!r}")
    inc = ["@ GENERATED by tools/mp/gen_tm_catalogue.py: the Game Corner's TM CATALOGUE (the PC game), every TM in its",
           "@ kind, for the TM counter's lists (data/scripts/mp_tm_catalogue.inc). Do not edit by hand.", ""]
    for kind, label in KINDS:
        inc += ["\t.align 2", f"MauvilleCity_GameCorner_Pokemart_{label}::"]
        for r in rows:
            if r["category"] == kind:
                inc.append(f"\t.2byte {item(r['tm'])} @ TM{r['tm']:02d} {r['name']} ({r['type']}), {r['coins']} coins")
        inc += ["\tpokemartlistend", ""]
    with open(os.path.join(ROOT, "data", "scripts", "mp_tm_catalogue_lists.inc"), "w") as out:
        out.write("\n".join(inc))
    h = ["// GENERATED by tools/mp/gen_tm_catalogue.py: the Game Corner coin price of every TM in the TM CATALOGUE (the PC",
         "// game; the owner's prices of 2026-10-31). Do not edit by hand.", "",
         f"#define MP_TM_CATALOGUE_COUNT {len(rows)}", f"#define MP_TM_CATALOGUE_LIST_COUNT {len(KINDS)}", ""]
    h += [f"extern const u16 MauvilleCity_GameCorner_Pokemart_{label}[];" for _, label in KINDS]
    h += ["", "static const u16 *const sMPTmCatalogueLists[MP_TM_CATALOGUE_LIST_COUNT] =", "{"]
    h += [f"    MauvilleCity_GameCorner_Pokemart_{label}," for _, label in KINDS]
    h += ["};", "", "struct MPTmCataloguePrice { u16 item; u32 coins; };",
          "static const struct MPTmCataloguePrice sMPTmCataloguePrices[MP_TM_CATALOGUE_COUNT] =", "{"]
    h += [f"    {{ITEM_TM{r['tm']:02d}, {r['coins']}}}, // {r['name']} ({r['category']})" for r in rows]
    h += ["};", ""]
    with open(os.path.join(ROOT, "src", "platform", "mp_tm_catalogue.h"), "w") as out:
        out.write("\n".join(h))
    print(f"{len(rows)} TMs: " + ", ".join(f"{label} {sum(r['category'] == k for r in rows)}" for k, label in KINDS))


if __name__ == "__main__":
    main()
