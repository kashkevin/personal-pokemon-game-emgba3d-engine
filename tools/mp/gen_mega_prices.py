#!/usr/bin/env python3
"""Generate the Game Corner coin price of every Mega Stone the Mauville dealer sells (Update 29).

The price is a pure function of the stone's Mega form (no randomness, no tuning by hand), so the list can be regenerated and
checked at any time:

    Mega form (from src/data/pokemon/species_info, the pinned engine)            coins
    restricted legendary (Mewtwo X/Y, Zygarde)                                    100,000
    sub-legendary / Mythical (Latias, Latios, Heatran, Darkrai, Diancie, ...)       90,000
    base stat total 700 (Garchomp, Salamence, Metagross, Tyranitar, Dragonite...)   80,000
    base stat total 620-699 (Starter and pseudo-final Megas, Gyarados, ...)         60,000   <- "rare"
    base stat total 590-619                                                         40,000   <- "common"
    base stat total 561-589                                                         35,000
    base stat total up to 560                                                       30,000

Sold as the third part of the Mega Evolution unlock: the Mega Ring (25,000 coins) first, then the stones here, all in Game
Corner coins. The output is src/platform/mp_mega_prices.h; --markdown prints the table for the documentation.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_world_events as gw  # noqa: E402
import gen_wild_pool as pool  # noqa: E402

ENGINE = gw.ENGINE
SHOP = ENGINE / "data/scripts/mp_mega_stone_shop.inc"
OUTPUT = ENGINE / "src/platform/mp_mega_prices.h"

# (minimum base stat total, coins), highest first; legendary classes are handled before
BANDS = ((700, 80_000), (620, 60_000), (590, 40_000), (561, 35_000), (0, 30_000))
PRICE_RESTRICTED = 100_000
PRICE_SUB_LEGENDARY = 90_000
MEGA_RING_COINS = 25_000
SHINY_CHARM_COINS = 100_000


def price_of(bst: int, flags: set) -> int:
    if "isRestrictedLegendary" in flags:
        return PRICE_RESTRICTED
    if flags & {"isSubLegendary", "isMythical"}:
        return PRICE_SUB_LEGENDARY
    for minimum, coins in BANDS:
        if bst >= minimum:
            return coins
    raise AssertionError


def stones() -> list[str]:
    return re.findall(r"\.2byte (ITEM_\w+)", SHOP.read_text(encoding="utf-8"))


def build() -> list[tuple[str, str, int, int]]:
    """(stone, Mega species, base stat total, coins) in the shop's order."""
    all_ids = gw.enum_all("include/constants/species.h", "Species", "SPECIES_")
    pre = pool.preprocess()
    changes = gw.form_changes(pre)
    targets = {t for _, t, _ in changes}
    wanted = {n: v for n, v in all_ids.items() if 1 <= v <= gw.MAX_DEX or n in targets}
    species = pool.parse_species(pre, wanted)
    pool.species_ids = {n: wanted[n] for n in species}
    pool.evaluate_stats(species)
    by_stone = {}
    for method, target, param in changes:
        if method.endswith("_ITEM") and param not in by_stone and target in species:
            by_stone[param] = target
    out = []
    for stone in stones():
        target = by_stone[stone]
        info = species[target]
        bst = sum(int(info[k]) for k in ("baseHP", "baseAttack", "baseDefense", "baseSpeed", "baseSpAttack", "baseSpDefense"))
        out.append((stone, target, bst, price_of(bst, info["flags"])))
    return out


def write(rows) -> None:
    lines = ["// GENERATED by tools/mp/gen_mega_prices.py: the Game Corner coin price of every Mega Stone the dealer sells.",
             "// Do not edit by hand. The price follows the Mega form's strength (see the generator); owned stones are not touched.",
             "",
             f"#define MP_MEGA_STONE_PRICE_MIN {min(r[3] for r in rows)}",
             f"#define MP_MEGA_STONE_PRICE_MAX {max(r[3] for r in rows)}",
             f"#define MP_MEGA_STONE_COUNT {len(rows)}",
             "",
             "struct MPMegaStonePrice { u16 item; u32 coins; };",
             "static const struct MPMegaStonePrice sMPMegaStonePrices[MP_MEGA_STONE_COUNT] =",
             "{"]
    for stone, target, bst, coins in rows:
        lines.append(f"    {{{stone}, {coins}}}, // {target.removeprefix('SPECIES_')} (base stat total {bst})")
    lines.append("};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def markdown(rows) -> str:
    out = ["| Mega Stone | Mega form | Base stat total | Coins |", "|---|---|---:|---:|"]
    for stone, target, bst, coins in sorted(rows, key=lambda r: (r[3], r[2], r[0])):
        out.append(f"| {stone.removeprefix('ITEM_').replace('_', ' ').title()} | {target.removeprefix('SPECIES_').replace('_', ' ').title()} | {bst} | {coins:,} |")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--markdown", action="store_true")
    parser.add_argument("--check", action="store_true", help="fail when the committed header is not what the generator makes")
    args = parser.parse_args()
    rows = build()
    if args.markdown:
        print(markdown(rows))
        return 0
    if args.check:
        before = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        write(rows)
        after = OUTPUT.read_text(encoding="utf-8")
        if before != after:
            OUTPUT.write_text(before, encoding="utf-8")
            print("mp_mega_prices.h is out of date")
            return 1
        print(f"mp_mega_prices.h is current ({len(rows)} stones)")
        return 0
    write(rows)
    counts = {}
    for row in rows:
        counts[row[3]] = counts.get(row[3], 0) + 1
    print(f"wrote {OUTPUT.name}: {len(rows)} stones, " + ", ".join(f"{k:,}: {v}" for k, v in sorted(counts.items())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
