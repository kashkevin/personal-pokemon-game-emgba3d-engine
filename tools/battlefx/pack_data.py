#!/usr/bin/env python3
"""Packs the Battle FX integration package's native data into the game's battlefx/ folder.

The game's Battle FX (include/diorama/battle_fx.h) reads, beside the executable:

  battlefx/bfx_core.js          the animation core (the Battle FX Lab's code, one script)
  battlefx/bfx_moves.json       the converted animations: 621 moves, 83 battle animations
  battlefx/shaders/*.vert|frag  the effect shaders (GLSL 3.30, the Lab's, generated by the package)
  battlefx/assets/atlas.png, ramps.png, strips.png
                                the effect textures (procedural: no game or Nintendo art)
  battlefx/assets/meshes.bin    the effect meshes (assets/meshes.json in a form C reads directly)
  battlefx/assets/info.txt      atlas grid, ramp rows, mesh kinds (from assets/info.json)
  battlefx/MANIFEST.txt         where it all came from, and each file's SHA-256
  battlefx/settings.cfg         development settings (enabled=1, log=0)

Usage: pack_data.py --package <battlefx_kit/native> [--out battlefx] [--source "<what the package is>"]

Only reads the package. Every file but meshes.bin / info.txt / MANIFEST.txt / settings.cfg is copied byte for byte.
"""
import argparse
import hashlib
import json
import shutil
import struct
import sys
from pathlib import Path

SHADERS = ["card.vert", "card.frag", "dist.frag", "particle.vert", "particle.frag", "ribbon.vert", "ribbon.frag",
           "mesh.vert", "mesh.frag", "lit.glsl", "fsq.vert", "bright.frag", "down.frag", "up.frag",
           "game_sprite.vert", "game_sprite.frag"]
TEXTURES = ["atlas.png", "ramps.png", "strips.png"]


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def pack_meshes(meshes, kinds, out):
    """meshes.bin: 'BFXM', u32 version 1, u32 kinds; per kind: name (16 bytes, NUL padded), u32 vertex count,
    11 floats material (colour 3, emissive 3, rim 3, roughness, metalness), then per vertex 9 floats
    (position 3, normal 3, colour 3). Little-endian."""
    data = bytearray(b"BFXM" + struct.pack("<II", 1, len(kinds)))
    for k in kinds:
        g = meshes[k]
        pos, nor = g["positions"], g["normals"]
        nv = len(pos) // 3
        col = g.get("colors") or []
        if len(col) != nv * 3:
            col = [1.0] * (nv * 3)
        mat = g.get("material", {})
        name = k.encode("ascii")
        if len(name) >= 16:
            sys.exit(f"mesh kind name too long: {k}")
        data += name + b"\0" * (16 - len(name))
        data += struct.pack("<I", nv)
        m = list(mat.get("color", [1, 1, 1])) + list(mat.get("emissive", [0, 0, 0])) + list(mat.get("rim", [0, 0, 0])) \
            + [mat.get("roughness", 1.0), mat.get("metalness", 0.0)]
        data += struct.pack("<11f", *m)
        for i in range(nv):
            data += struct.pack("<9f", *pos[i * 3:i * 3 + 3], *nor[i * 3:i * 3 + 3], *col[i * 3:i * 3 + 3])
    out.write_bytes(bytes(data))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--package", required=True, help="the Battle FX package's native/ folder")
    ap.add_argument("--out", default="battlefx")
    ap.add_argument("--source", default="", help="what the package is (tag, commit), for MANIFEST.txt")
    a = ap.parse_args()
    pkg, out = Path(a.package), Path(a.out)
    (out / "shaders").mkdir(parents=True, exist_ok=True)
    (out / "assets").mkdir(parents=True, exist_ok=True)
    files = []
    for name, dst in (("js/bfx_core.js", "bfx_core.js"), ("data/bfx_moves.json", "bfx_moves.json")):
        shutil.copyfile(pkg / name, out / dst)
        files.append(dst)
    for s in SHADERS:
        shutil.copyfile(pkg / "shaders" / s, out / "shaders" / s)
        files.append("shaders/" + s)
    for t in TEXTURES:
        shutil.copyfile(pkg / "assets" / t, out / "assets" / t)
        files.append("assets/" + t)
    info = json.loads((pkg / "assets/info.json").read_text())
    meshes = json.loads((pkg / "assets/meshes.json").read_text())
    kinds = info["meshKinds"]
    pack_meshes(meshes, kinds, out / "assets/meshes.bin")
    files.append("assets/meshes.bin")
    (out / "assets/info.txt").write_text(
        "atlasGrid %d\nrampRows %d\nribbonRows %d\nmeshKinds %s\n"
        % (info["atlasGrid"], info.get("rampRows", 0), info.get("ribbonRowsCount", 8), " ".join(kinds)))
    files.append("assets/info.txt")
    settings = out / "settings.cfg"
    if not settings.exists():
        settings.write_text("# Battle FX development settings (include/diorama/battle_fx.h); the environment\n"
                            "# variables PKMN_BATTLEFX and PKMN_BATTLEFX_LOG override them.\n"
                            "# enabled=0 plays the original GBA animations.\n"
                            "enabled=1\nlog=0\n")
    lines = ["Battle FX data for the game's 3D battles (include/diorama/battle_fx.h).",
             "Packed by tools/battlefx/pack_data.py from the Battle FX integration package's native/ folder"
             + (f" ({a.source})" if a.source else "") + ".",
             "The textures and meshes are procedural (no game or Nintendo art); the animation data is converted from",
             "pokeemerald-expansion's own battle_anim_scripts.s (commit in bfx_moves.json meta.commit).",
             ""]
    lines += [f"{sha256(out / f)}  {f}" for f in sorted(files)]
    (out / "MANIFEST.txt").write_text("\n".join(lines) + "\n")
    print(f"packed {len(files)} files into {out}")


if __name__ == "__main__":
    main()
