def constants_text(floors, h):
    out = ["#ifndef GUARD_CONSTANTS_TOWER_LEGENDS_H\n", "#define GUARD_CONSTANTS_TOWER_LEGENDS_H\n", "\n",
           "// Battle Tower: Legends (PC only). %s - do not edit by hand.\n" % GENERATED,
           "// The trainers of src/data/tower_legends.party, in order: each floor's solo trainer, Duo A and Duo B.\n",
           "\n", "#define TOWER_FLOOR_COUNT 100\n", "\n"]
    i = 0
    for f in floors:
        for t in (f["solo"], f["duoA"], f["duoB"]):
            out.append("#define %-32s %d\n" % (t.id, i))
            i += 1
    out += ["\n", "#define TOWER_LEGENDS_TRAINER_COUNT %d\n" % i,
            "// CRC-32 of the canonical JSON of the floors (tools/tower_legends/tower_legends.json \"hash\").\n",
            "#define TOWER_LEGENDS_TABLE_HASH 0x%08xu\n" % h, "\n",
            "#define TOWER_FLOOR_REGULAR 0\n", "#define TOWER_FLOOR_BOSS 1\n", "#define TOWER_FLOOR_SPECIAL 2\n",
            "#define TOWER_FLOOR_FINAL 3\n", "\n", "#define TOWER_REGION_KANTO 0\n", "#define TOWER_REGION_HOENN 1\n",
            "\n", "#endif // GUARD_CONSTANTS_TOWER_LEGENDS_H\n"]
    return "".join(out)


