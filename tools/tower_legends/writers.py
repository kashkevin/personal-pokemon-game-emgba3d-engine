def trainer_literal(t, indent):
    pad = " " * indent
    parts = []
    for k, v in t.items():
        if k == "mons":
            mons = ",\n".join(pad + "        " + py_literal(m) for m in v)
            parts.append('%s    "mons": [\n%s,\n%s    ]' % (pad, mons, pad))
        else:
            parts.append("%s    %s: %s" % (pad, json.dumps(k), py_literal(v)))
    return "{\n" + ",\n".join(parts) + ",\n" + pad + "}"


# ----- FLOORS.md ------------------------------------------------------------------------------------------------
def md_mon(g, nm, m):
    item = nm.item(m.item) if m.item else "-"
    moves = ", ".join(nm.move(c) for c in m.moves)
    mega = " (%s)" % nm.display_mega(m.mega, m.species) if m.mega else ""
    evs = " / ".join("%d %s" % (v, s) for v, s in zip(m.evs, STATS) if v) or "-"
    ivs = "%d" % m.ivs[0] if len(set(m.ivs)) == 1 else "/".join(str(v) for v in m.ivs)
    return "| %s%s | %s | %s | %s | %s | %s | %s |" % (
        nm.display_species(m.species), mega, item, nm.ability(m.ability),
        naming.party_field("NATURE", m.nature), ivs, evs, moves)


def class_print(g, trainer_class):
    """The class as the game prints it (the dump writes the game's glyphs as plain characters: {PKMN} as two
    spaces, the e of POKe as a space, the gender signs as M and F)."""
    name = g.classes[g.class_values[trainer_class]]["name"]
    if name.startswith("   "):
        name = "PKMN " + name[3:]
    name = name.replace("POK ", "POK\u00e9")
    if name in ("SWIMMERM", "SWIMMERF"):
        name = name[:-1] + ("\u2642" if name.endswith("M") else "\u2640")
    return name.strip()


def md_trainer(g, nm, t, label):
    cls = class_print(g, t.trainer_class)
    lines = ["%s: **%s %s** (%s, %s, %s; AI: %s)" % (label, cls, t.name, t.trainer_class[14:], t.pic[12:],
                                                     t.gender.lower(), ", ".join(a[8:] for a in t.ai)),
             "", "| Pokemon | Item | Ability | Nature | IVs | EVs | Moves |", "| --- | --- | --- | --- | --- | --- | --- |"]
    lines += [md_mon(g, nm, m) for m in t.mons]
    return lines


def floors_md_text(g, floors, h, report, notes, dump_note):
    nm = Names(g)
    out = ["# Battle Tower: Legends - the floors", "",
           "%s from the game's own data (`pokeemerald-mp --dump-tower-data`); do not edit by hand. Table hash "
           "`0x%08x` (TOWER_LEGENDS_TABLE_HASH)." % (GENERATED, h), "",
           "Every opposing Pokemon is exactly the floor's level. Columns: held item, Ability, nature, IVs (one number "
           "when all six are equal), EVs, moves; a Mega Stone holder shows its Mega form. Duo A is the floor's solo "
           "trainer with three of its team (its ace and its best), Duo B the partner. Texts use the game's escapes "
           "(\\n a new line, \\p a new page).", ""]
    # boss roster
    out += ["## Boss roster", "",
            "| Floor | Kind | Boss | Class (prints) | Picture (source) | Mega | Battle music | Duo partner (class, picture) |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for f in floors:
        if f["kind"] == "regular":
            continue
        s, p = f["solo"], f["duoB"]
        mega = ", ".join(nm.display_mega(m.mega, m.species) for m in s.mons if m.mega) or "-"
        cls = class_print(g, s.trainer_class)
        pcls = class_print(g, p.trainer_class)
        out.append("| %d | %s | %s | %s (%s) | %s (%s) | %s | %s | %s %s (%s, %s) |" % (
            f["floor"], f["kind"], s.name, s.trainer_class[14:], cls, s.pic[12:], f["pic_source"], mega, f["music"],
            pcls, p.name, p.trainer_class[14:], p.pic[12:]))
    out += ["", "Picture sources: FRLG pictures are TRAINER_PIC_*_FRLG plus RED and LEAF (FireRed/LeafGreen "
            "art); the others are Emerald's. Class names print as the game's trainer class table writes them "
            "(`PKMN` is the game's {PKMN} glyph).", ""]
    # deviations
    out += ["## Substitutions and deviations from the design", ""]
    for d in bosses.DEVIATIONS:
        out.append("* " + d)
    for d in GENERAL_DEVIATIONS:
        out.append("* " + d)
    for d in notes:
        out.append("* " + d)
    out.append("")
    # validation
    out += ["## Validation", "",
            "%d rule checks over %d rules, %d violations (`generate.py --verify-trainerproc` also compares "
            "trainerproc's output with every trainer and Pokemon).%s" % (
                sum(report.counts.values()), len(report.counts), len(report.errors),
                (" " + dump_note) if dump_note else ""), "",
            "| Floors | Mean team BST | Mean IV | Mean EV total | Team size | AI tier |",
            "| --- | --- | --- | --- | --- | --- |"]
    for band, bst, iv, ev, size, tier in report.facts["bands"]:
        out.append("| %d-%d | %.0f | %.1f | %.0f | %.1f | %d |" % (band * 10 + 1, band * 10 + 9 if band < 9 else 99,
                                                                 bst, iv, ev, size, tier))
    out.append("")
    # one line per floor
    out += ["## Floor list", "", "| Floor | Kind | Solo trainer | Team | Ace | Duo B |", "| --- | --- | --- | --- | --- | --- |"]
    for f in floors:
        s, p = f["solo"], f["duoB"]
        ace = s.mons[-1]
        out.append("| %d | %s | %s %s | %d | %s | %s %s |" % (
            f["floor"], f["kind"], class_print(g, s.trainer_class), s.name, len(s.mons),
            nm.display_mega(ace.mega, ace.species) if ace.mega else nm.display_species(ace.species),
            class_print(g, p.trainer_class), p.name))
    out.append("")
    # floors
    out += ["## Floors", ""]
    for f in floors:
        n = f["floor"]
        flags = [f["kind"]] + (["checkpoint"] if f["checkpoint"] else [])
        out.append("### Floor %d (%s; %s; difficulty %d; %s)" % (n, ", ".join(flags), f["region"], f["difficulty"],
                                                                f["music"]))
        out.append("")
        out.append("Intro: `%s`  " % f["intro"])
        out.append("Defeat: `%s`  " % f["defeat"])
        out.append("Defeat (Duo B): `%s`" % f["defeatB"] + ("  " if f["victory"] else ""))
        if f["victory"]:
            out.append("Victory: `%s`" % f["victory"])
        out.append("")
        out += md_trainer(g, nm, f["solo"], "Solo")
        out.append("")
        a = f["duoA"]
        out.append("Duo A: %s brings %s." % (a.name, ", ".join(nm.display_species(m.species) for m in a.mons)))
        out.append("")
        out += md_trainer(g, nm, f["duoB"], "Duo B")
        out.append("")
    return "\n".join(out) + "\n"


