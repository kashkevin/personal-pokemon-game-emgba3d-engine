def party_text(g, floors, h):
    nm = Names(g)
    out = []
    out.append("/*\n")
    out.append("%s - do not edit by hand.\n" % GENERATED)
    out.append("Battle Tower: Legends (PC only): 100 floors, each with its solo trainer and the Duo pair\n")
    out.append("(TOWER_TRAINER_FNNN, _DUO_A, _DUO_B; include/constants/tower_legends.h). Every Pokemon is written\n")
    out.append("out in full and its level is the floor's. Change tools/tower_legends/ (the pools, bosses.py or the\n")
    out.append("rules) and run tools/tower_legends/generate.py --data <the game's dump> again.\n")
    out.append("Table hash (TOWER_LEGENDS_TABLE_HASH): 0x%08x\n" % h)
    out.append("*/\n")
    for f in floors:
        for t in (f["solo"], f["duoA"], f["duoB"]):
            out.append("\n=== %s ===\n" % t.id)
            out.append("Name: %s\n" % t.name)
            out.append("Class: %s\n" % naming.party_field("TRAINER_CLASS", t.trainer_class))
            out.append("Pic: %s\n" % naming.party_field("TRAINER_PIC", t.pic))
            out.append("Gender: %s\n" % t.gender)
            out.append("Music: %s\n" % naming.party_field("TRAINER_ENCOUNTER_MUSIC", t.music))
            out.append("Battle Type: Singles\n")
            out.append("AI: %s\n" % " / ".join(naming.party_field("AI_FLAG", a) for a in t.ai))
            for m in t.mons:
                out.append("\n")
                head = nm.species(m.species)
                if m.item:
                    head += " @ " + nm.item(m.item)
                out.append(head + "\n")
                out.append("Level: %d\n" % m.level)
                out.append("Ability: %s\n" % nm.ability(m.ability))
                out.append("IVs: %s\n" % " / ".join("%d %s" % (v, s) for v, s in zip(m.ivs, STATS)))
                if any(m.evs):
                    out.append("EVs: %s\n" % " / ".join("%d %s" % (v, s) for v, s in zip(m.evs, STATS) if v))
                out.append("%s Nature\n" % naming.party_field("NATURE", m.nature))
                for mv in m.moves:
                    out.append("- %s\n" % nm.move(mv))
    return "".join(out)


