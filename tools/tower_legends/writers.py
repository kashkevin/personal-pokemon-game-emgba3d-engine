        out.append("        .difficulty = %d,\n" % f["difficulty"])
        out.append("        .solo = %s,\n" % f["solo"].id)
        out.append("        .duoA = %s,\n" % f["duoA"].id)
        out.append("        .duoB = %s,\n" % f["duoB"].id)
        out.append("        .battleMusic = %s,\n" % f["music"])
