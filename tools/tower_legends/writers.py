        out.append("    {\n")
        for k, v in f.items():
            if k in ("solo",):
                out.append("        %s: %s,\n" % (json.dumps(k), trainer_literal(v, 8)))
            elif k == "duo":
                out.append('        "duo": [\n')
                for t in v:
                    out.append("            %s,\n" % trainer_literal(t, 12))
