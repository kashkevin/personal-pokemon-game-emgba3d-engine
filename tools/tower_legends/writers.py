class Names:
    """The .party spellings and the display names of the game's constants."""

    def __init__(self, g):
        self.g = g

    def species(self, const):
        s = self.g.species_by_const[const]
        return naming.party_name("SPECIES", const, s.name)

    def move(self, const):
        return naming.party_name("MOVE", const, self.g.moves[self.g.move(const)]["name"])

    def item(self, const):
        return naming.party_name("ITEM", const, self.g.items[self.g.item(const)]["name"])

    def ability(self, const):
        return naming.party_name("ABILITY", const, self.g.abilities[self.g.ability(const)]["name"])

    def display_species(self, const):
        special = {"SPECIES_NIDORAN_F": "Nidoran F", "SPECIES_NIDORAN_M": "Nidoran M", "SPECIES_FLABEBE_RED": "Flabebe",
                   "SPECIES_MEOWSTIC_M": "Meowstic", "SPECIES_MR_MIME": "Mr. Mime", "SPECIES_MIME_JR": "Mime Jr."}
        if const in special:
            return special[const]
        name = self.g.species_by_const[const].name
        if name and all(32 <= ord(c) < 127 for c in name) and "  " not in name and name.strip() == name:
            return name
        return naming.title_from_constant(const, "SPECIES")

    def display_mega(self, mega_const, base_const):
        """A Mega form as the games name it: Mega Charizard X, Mega Gyarados."""
        m = re.search(r"_MEGA(?:_([A-Z]))?$", mega_const)
        suffix = m.group(1) if m and m.group(1) else ""
        return "Mega %s%s" % (self.display_species(base_const), (" " + suffix) if suffix else "")


# ----- JSON (the app's and the tests' copy) ---------------------------------------------------------------------
def mon_json(g, m):
    return {
        "species": m.species, "speciesId": g.species_by_const[m.species].id, "level": m.level,
        "item": m.item, "itemId": g.item(m.item) if m.item else 0,
        "ability": m.ability, "abilityId": g.ability(m.ability),
        "nature": m.nature, "natureId": g.natures[m.nature],
        "ivs": list(m.ivs), "evs": list(m.evs),
        "moves": list(m.moves), "moveIds": [g.move(c) for c in m.moves] + [0] * (4 - len(m.moves)),
        "mega": m.mega,
    }


def trainer_json(g, t):
    return {
        "id": t.id, "name": t.name, "class": t.trainer_class, "classId": g.class_values[t.trainer_class],
        "pic": t.pic, "picId": g.pic_values[t.pic], "gender": t.gender.lower(), "encounterMusic": t.music,
        "ai": list(t.ai), "mons": [mon_json(g, m) for m in t.mons],
    }


def floors_json(g, floors):
    out = []
    for f in floors:
        out.append({
            "floor": f["floor"], "level": f["floor"], "kind": f["kind"], "checkpoint": f["checkpoint"],
            "region": f["region"], "difficulty": f["difficulty"], "music": f["music"], "intro": f["intro"],
            "defeat": f["defeat"], "defeatB": f["defeatB"], "victory": f["victory"],
            "solo": trainer_json(g, f["solo"]), "duo": [trainer_json(g, f["duoA"]), trainer_json(g, f["duoB"])],
        })
    return out


def table_hash(floors_js):
    return zlib.crc32(json.dumps(floors_js, sort_keys=True, separators=(",", ":")).encode()) & 0xFFFFFFFF


def json_text(floors_js, h):
    return json.dumps({"version": 1, "hash": "0x%08x" % h, "floors": floors_js}, indent=1) + "\n"


