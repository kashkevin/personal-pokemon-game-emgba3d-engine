"""Curated, themed pools for the regular floors of Battle Tower: Legends (tools/tower_legends/generate.py).

Each regular trainer class of Emerald has: its trainer class and pictures (with the picture's gender), its encounter
music (the house mapping of src/data/trainers.party), the floors it appears on (weaker classes low, stronger high),
a pool of species that fits its theme, the classes that make a fitting Duo partner, and a few lines it says when beaten.

A pool entry names the line's goal species; the generator uses the most evolved stage of that line that is legal at
the floor's level (gamedata.Game.min_level), so the same pool gives Geodude on floor 6, Graveler on floor 25 and Golem
on floor 30. Names are uppercase and at most 10 characters, like the game's trainer data; no name is used twice.
"""


