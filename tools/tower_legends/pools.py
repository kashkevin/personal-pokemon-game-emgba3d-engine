        self.pool = ["SPECIES_" + s for s in pool]
        self.partners = partners          # keys of fitting Duo partner classes, best first
        self.lines = lines                # defeat lines (the game's text: \n line break, at most 2 lines)
        self.intro_name = intro_name      # the class as the field text writes it (default: the game's class name)


