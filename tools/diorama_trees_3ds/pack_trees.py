#!/usr/bin/env python3
"""Pack the 3DS project's tree art into one RGBA texture for the Diorama renderer.

Port of ZallaxDev/pokeemerald-3Ds-dualscreen `3ds_port/scripts/gen_voxel_trees.py`
(commit 4a699e3, MIT; see README.md here): the same 128x128 layout - large crown at
0,0, large trunk at 32,0, small crown at 32,32, small trunk at 48,32, Dewford's small
crown at 64,0 and its trunk at 80,0 - with the same one-bit alpha (opaque from 128),
but as RGBA8 rows from the top, the way OpenGL takes them, written as C source for
`src/diorama/gl/gl_tree_sprites.c`.
"""

import argparse
from pathlib import Path

from PIL import Image

DIM = 128
SOURCES = (("tree_crown.png", (32, 36), (0, 0)),
           ("tree_trunk.png", (32, 32), (32, 0)),
           ("tree_small_crown.png", (16, 32), (32, 32)),
           ("tree_small_trunk.png", (16, 16), (48, 32)),
           ("tree_2_small_crown.png", (16, 32), (64, 0)),
           ("tree_2_small_trunk.png", (16, 16), (80, 0)))


def pack(art):
    atlas = Image.new("RGBA", (DIM, DIM), (0, 0, 0, 0))
    for name, size, origin in SOURCES:
        with Image.open(art / name) as source:
            if source.size != size:
                raise ValueError(f"{name}: expected {size}, got {source.size}")
            atlas.paste(source.convert("RGBA"), origin)
    pixels = bytearray(atlas.tobytes())
    for i in range(0, len(pixels), 4):
        if pixels[i + 3] >= 128:
            pixels[i + 3] = 255
        else:
            pixels[i:i + 4] = b"\0\0\0\0"
    return bytes(pixels)


def main():
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--art", type=Path, default=here / "art")
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    args = parser.parse_args()
    pixels = pack(args.art)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(
        "/* Generated by tools/diorama_trees_3ds/pack_trees.py: do not edit. */\n"
        "#ifndef GUARD_DIORAMA_TREES_3DS_GENERATED_H\n"
        "#define GUARD_DIORAMA_TREES_3DS_GENERATED_H\n\n"
        "#include <stdint.h>\n\n"
        f"#define DIORAMA_TREES_3DS_DIM {DIM}\n"
        "/* RGBA8, rows from the top; see pack_trees.py for the layout. */\n"
        "extern const uint8_t gDioramaTrees3dsRgba[DIORAMA_TREES_3DS_DIM * DIORAMA_TREES_3DS_DIM * 4];\n\n"
        "#endif\n")
    lines = []
    for row in range(0, len(pixels), 32):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in pixels[row:row + 32]) + ",")
    args.source.parent.mkdir(parents=True, exist_ok=True)
    args.source.write_text(
        "/* Generated by tools/diorama_trees_3ds/pack_trees.py from the 3DS project's\n"
        " * tree art (MIT, see tools/diorama_trees_3ds/README.md): do not edit. */\n"
        "#include \"diorama/trees_3ds.generated.h\"\n\n"
        "const uint8_t gDioramaTrees3dsRgba[DIORAMA_TREES_3DS_DIM * DIORAMA_TREES_3DS_DIM * 4] = {\n"
        + "\n".join(lines) + "\n};\n")
    print(f"diorama trees (3DS): {DIM}x{DIM} RGBA -> {args.source}")


if __name__ == "__main__":
    main()
