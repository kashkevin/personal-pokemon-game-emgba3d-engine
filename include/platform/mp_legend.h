#ifndef GUARD_PLATFORM_MP_LEGEND_H
#define GUARD_PLATFORM_MP_LEGEND_H

// Random Legendary and Mythical wild encounters (Update 29), native PC build only (src/platform/mp_legend.c).
//
// One roll per eligible random wild encounter: 1 in 6,000 outside the Safari Zone, 1 in 4,000 inside it. This is the chance of
// ANY Legendary or Mythical Pokemon, not of each species. On a hit the species is chosen uniformly from the pool of the
// place: outside the Safari Zone the Legendaries and Mythicals whose habitat tags fit the area (and the time of day, for the
// two night-only species); inside it all of them. The encounter keeps the level the map's own encounter table chose (no
// minimum, no override), and the Pokemon is an ordinary level-N Pokemon of its species. Scripted, static, roaming, outbreak
// and Feebas encounters never roll. src/data/mp_legend_data.h is generated by tools/mp/gen_legend_pool.py.
#include "global.h"
#include "wild_encounter.h"
#include "platform/mp_legend_tags.h"

struct MPLegendSpecies
{
    u16 species;
    u16 habitats;   // MP_LEGEND_* tags: the area tags that make the species eligible
    u8 flags;       // MP_LEGEND_NIGHT_ONLY
};

struct MPLegendMapsecTags
{
    u8 mapsec;
    u16 tags;
};

struct MPLegendWeatherTag
{
    u8 weather;
    u16 tag;
};

// The habitat tags of an encounter area: the encounter method (land, rocks, surfing, fishing), the map's section and type,
// the weather (not underground) -- the same inputs the host's shared spawns use.
u32 MPLegend_AreaHabitats(enum WildPokemonArea area, u32 mapsec, u32 mapType, u32 weather);

// The chance, exactly: random in [0, 2^32) hits when random * oneIn < 2^32.
bool32 MPLegend_RollHits(u32 random, bool32 safari);
u32 MPLegend_OneIn(bool32 safari);

// Eligible species of a place, and the uniform pick among them (random in [0, 2^32)); SPECIES_NONE for an empty pool.
u32 MPLegend_PoolSize(u32 habitats, bool32 night, bool32 safari);
u16 MPLegend_PoolSpecies(u32 habitats, bool32 night, bool32 safari, u32 index);
u16 MPLegend_Pick(u32 habitats, bool32 night, bool32 safari, u32 random);

u32 MPLegend_SpeciesCount(void);
const struct MPLegendSpecies *MPLegend_SpeciesAt(u32 index);

// Game glue: the generator of a random wild encounter notes the Pokemon it made (TryGenerateWildMon, fishing, and an
// overworld Pokemon the player walks into); BattleSetup_StartWildBattle then rolls once for it.
void MPLegend_NoteWildMon(enum WildPokemonArea area);
void MPLegend_ApplyToPendingWildBattle(void);
void MPLegend_ForgetPending(void);

// A Legendary or Mythical species (the species data's flags). Such a Pokemon met in the wild stays there until it is
// caught or knocked out (the owner's request of 2026-10-27: src/wild_encounter_ow.c), and is never rolled again.
bool32 MPLegend_IsLegendSpecies(u16 species);
// The Legendary or Mythical the roll made of the wild battle now ending (FALSE for none), forgotten once read: the
// visible Pokemon the battle came from is that Pokemon from then on (MPOWE_OnWildBattleEnd).
bool32 MPLegend_TakeBattleLegend(u16 *species, bool8 *shiny, bool8 *female);

// Test hook (the self-tests and the test builds' PKMN_TEST_LEGEND): 1 = every roll hits, -1 = none does, 0 = the real odds.
void MPLegend_TestForce(int mode);

#endif // GUARD_PLATFORM_MP_LEGEND_H
